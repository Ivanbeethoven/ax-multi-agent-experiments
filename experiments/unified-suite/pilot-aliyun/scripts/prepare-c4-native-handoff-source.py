#!/usr/bin/env python3
"""Install the frozen checkpoint once on the reviewed source mount, then export."""
import argparse
from contextlib import closing
from copy import deepcopy
from datetime import datetime, timezone
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import socket
import sqlite3
import stat
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[4]))
from bench.runtime import node
from bench.runtime.common import digest, load, mounts, pinned, private_dir, spec, write_new
from bench.session_check import check_after

SCHEMA = 'c4-native-handoff-source-install-v1'
POINT = Path('/srv/ax-pilot-session')
CONFIG = 'config/opencode.json'
MODEL = 'deepseek-v4-flash'
DUMMY_KEY = 'local-session-no-master-key'
OLD_RELAY_PORT = 18443
PHASE_TIMEOUT_SECONDS = 60


class InstallError(ValueError):
    pass


def require(ok, message):
    if not ok:
        raise InstallError(message)


def regular(pin, name=None):
    path = pinned(pin)
    require(path.resolve(strict=True) == path and path.is_file() and
            (name is None or path.name == name), 'Canonical pinned input file required')
    return path


def reference(path):
    return dict(path=str(path), sha256=digest(path))


def same_install_scope(point, path):
    return path == point or path.is_relative_to(point)


def source_tools(pin):
    path = regular(pin, 'prepare-session-input.py')
    require(path == Path(__file__).resolve().with_name(path.name), 'Pin the colocated original tree and sync helper')
    loader = importlib.util.spec_from_file_location('original_session_input', path)
    result = importlib.util.module_from_spec(loader)
    loader.loader.exec_module(result)
    return result


def mount_status(mount, point):
    mount_spec = spec(mount['spec'], 'experiment-mount-v1')
    directory = Path(mount['directory'])
    require(directory.is_absolute() and directory.resolve(strict=True) == directory and directory.is_dir() and
            not same_install_scope(point, directory), 'Original local mount supervisor required')
    ready = load(directory/'ready.json')
    current = node.control(directory, 'status')
    process_fields = ('pid', 'boot_id', 'start_ticks')
    process = {k: ready['process'][k] for k in process_fields}
    require(mount_spec['mount_point'] == str(point) and mount_spec['filesystem'] in ('juicefs', 'brewfs') and
            ready['spec'] == mount['spec'] and ready['anchor'] == mount_spec['anchor'] and
            ready['mount']['point'] == str(point) and mounts(point) == [ready['mount']] and
            all(current[k] == ready[k] for k in ('mount', 'anchor')) and
            all(current['process'][k] == process[k] for k in process_fields),
            'Original source mount instance changed or is not mounted')
    return mount_spec, dict(mount=ready['mount'],anchor=ready['anchor'],process=process)


def client_config(original, private, url):
    match = re.fullmatch(r'http://127\.0\.0\.1:([1-9][0-9]{3,4})/v1', url)
    require(match and 1024 <= int(match[1]) <= 65535 and int(match[1]) != OLD_RELAY_PORT,
            'Independent loopback relay endpoint required; do not reuse the old service')
    mode = private.stat()
    require(mode.st_uid == os.geteuid() and stat.S_IMODE(mode.st_mode) == 0o600,
            'Owner-only private client relay configuration required')
    old, new = load(original), load(private)
    old_provider = old['provider']['experiment']
    options = old_provider['options']
    require(old['model'] == 'experiment/'+MODEL and options.get('apiKey') == DUMMY_KEY and
            re.fullmatch(r'http://127\.0\.0\.1:[0-9]{1,5}/v1', options.get('baseURL', '')),
            'Checkpoint must contain the original dummy client configuration')
    key = new['provider']['experiment']['options'].get('apiKey', '')
    require(isinstance(key, str) and re.fullmatch('[0-9a-f]{64}', key),
            'Use the independent relay client key generated by the relay initializer')
    allowed = deepcopy(old)
    provider = allowed['provider']['experiment']
    provider['options'].update(baseURL=url, apiKey=key)
    provider['models'][MODEL]['limit'] = dict(context=0, output=512)
    require(new == allowed, 'Only the client relay URL/key and exact model limit may change')
    return new


def verify_source(request, workspace, tools):
    checkpoint_path = regular(request['checkpoint'], 'checkpoint.json')
    receipt = load(regular(request['checkpoint_receipt'], 'receipt.json'))
    original = checkpoint_path.parent/'workspace'
    point = load(checkpoint_path)
    require(original.resolve(strict=True) == original and original.is_dir() and
            point['canonical_workspace'] == str(workspace) and point['canonical_project'] == str(workspace/'repo') and
            point['source_process_exited'] is True and point['sqlite_quick_check'] == 'ok' and
            point['contains_provider_master_key'] is False and point.get('contains_active_relay_key', False) is False and
            receipt['passed'] is True and receipt['checkpoint_sha256'] == request['checkpoint']['sha256'] and
            receipt['session_id'] == point['session_id'] and receipt['contains_provider_master_key'] is False and
            receipt['contains_active_relay_key'] is False and
            receipt['opencode_sha256'] == point['opencode_binary_sha256'] == request['binary']['sha256'] and
            receipt['tree_reader_sha256'] == request['tree_reader']['sha256'],
            'Original closed checkpoint, package receipt, canonical paths and OpenCode must agree')
    before = tools.tree(original)
    from_receipt = {k.removeprefix('workspace/'):v for k,v in receipt['files'].items() if k.startswith('workspace/')}
    require(before and before == load(regular(request['source_tree'], 'source-tree.json')) == from_receipt,
            'Complete frozen checkpoint tree differs')
    require(all(not (row['mode'] & 0o7000) and not (
        row['type'] == 'symlink' and Path(row['target']).is_absolute()) and
        not (name.endswith(('.db-wal', '.db-journal')) and row.get('bytes', 0))
        for name,row in before.items()), 'Unsafe checkpoint link, mode, or open SQLite journal')
    native_export = original/'session-export.json'
    db_name = 'source/data/opencode/opencode.db'
    require(all(before.get(name, {}).get('type') == 'file' for name in (CONFIG, db_name, 'session-export.json')) and
            all(before.get(name, {}).get('type') == 'directory' for name in
                ('repo', *(f'source/{n}' for n in ('data','state','cache','config')))) and
            digest(native_export) == point['session_export_sha256'] and
            point['session_prefix']['session_id'] == point['session_id'],
            'Original native export/database and workspace-local state required')
    check_after(point['session_prefix'], load(native_export), False)
    db = original/db_name
    with closing(sqlite3.connect(db.as_uri()+'?mode=ro&immutable=1', uri=True)) as sql:
        require(sql.execute('PRAGMA quick_check').fetchall() == [('ok',)], 'Frozen native SQLite is not intact')
    return point, original, before


def run(request_ref, output):
    request = spec(request_ref, SCHEMA)
    source = request['source']
    require(set(source) == {'role','side','hostname','pool'} and
            source['role'] == 'client' and source['side'] == 'source' and
            source['hostname'] == socket.gethostname(), 'Run only on the reviewed source executor')
    tools = source_tools(request['tree_reader'])
    regular(request['binary'], 'opencode')
    worker = regular(request['worker'], 'session-worker-bounded.py')
    private = regular(request['private_client_config'])
    point = POINT
    workspace = point/'workspace'
    output = Path(output)
    require(point.resolve(strict=True) == point and point.is_dir() and
            output.is_absolute() and output.resolve() == output and not os.path.lexists(output) and
            not same_install_scope(point, output) and not same_install_scope(output, point),
            'Fresh canonical evidence output outside the tested mount required')
    for name in ('checkpoint','checkpoint_receipt','source_tree','binary','worker','tree_reader','private_client_config'):
        require(not same_install_scope(point, Path(request[name]['path']).resolve(strict=True)),
                'Inputs must be staged outside the original shared mount')
    mount_spec, identity = mount_status(request['mount'], point)
    require(mount_spec['cluster'] == source['pool'] and mount_spec['purpose'] == 'experiment' and
            not os.path.lexists(workspace),
            'The reviewed source pool must own a fresh shared workspace')
    checkpoint, original, before = verify_source(request, workspace, tools)
    settings = client_config(original/CONFIG, private, request['relay_url'])
    state = {name:str(workspace/'source'/name) for name in ('data','state','cache','config')}
    destination = workspace/CONFIG
    native = dict(action='export', binary=request['binary'], workspace=str(workspace), project=str(workspace/'repo'),
        config=str(destination), state=state, relay_url=request['relay_url'], session_id=checkpoint['session_id'],
        total_timeout_seconds=PHASE_TIMEOUT_SECONDS)
    output = private_dir(output)
    stage = 'copy'
    write_new(output/'started.json', dict(at=datetime.now(timezone.utc).isoformat(), request=request_ref,
        checkpoint=request['checkpoint'], mount=request['mount'], scope='Source-only checkpoint install and export',
        automatic_retry=False))
    try:
        require(mount_status(request['mount'], point)[1] == identity, 'Source mount changed before copy')
        shutil.copytree(original, workspace, symlinks=True)
        require(tools.tree(workspace) == before, 'Complete installed checkpoint differs')
        with os.fdopen(os.open(destination, os.O_WRONLY|os.O_NOFOLLOW|os.O_TRUNC), 'w', encoding='utf-8') as f:
            os.fchmod(f.fileno(), 0o600)
            json.dump(settings, f, ensure_ascii=False)
            f.write('\n')
            f.flush()
            os.fsync(f.fileno())
        synced = tools.sync_tree(workspace)
        after = tools.tree(workspace)
        require(set(after) == set(before) and all(after[k] == before[k] for k in before if k != CONFIG),
                'Only the prepared provider config may differ from the frozen tree')
        config_pin = reference(destination)
        stage = 'bounded-export'
        phase_file = output/'export-request.json'
        write_new(phase_file, native)
        export = output/'native-export'
        argv = [sys.executable, '-B', str(worker), '--request', str(phase_file),
            '--sha256', digest(phase_file), '--out', str(export)]
        with (output/'worker.stdout').open('xb') as stdout, (output/'worker.stderr').open('xb') as stderr:
            exit_code = subprocess.run(argv, stdin=subprocess.DEVNULL, stdout=stdout, stderr=stderr).returncode
        require(exit_code == 0, 'Bounded native export failed; retain receipts without retry')
        bounded, started = load(export/'bounded.json'), load(export/'started.json')
        require(bounded['passed'] is True and bounded['exit_code'] == 0 and
                bounded['descendants_cleared'] is True and bounded['timed_out'] is False and
                bounded['total_timeout_seconds'] == PHASE_TIMEOUT_SECONDS and
                started['action'] == 'export' and started['binary'] == request['binary'] and
                started['session_state']['home_empty_before_start'] is True and
                started['session_state']['config_sha256'] == config_pin['sha256'] and
                started['session_state']['xdg'] == state,
                'Exact export-only bounded worker and clean HOME receipt required')
        canonical = export/'export.json'
        require(canonical.is_file() and not canonical.is_symlink() and
                digest(canonical) == checkpoint['session_export_sha256'], 'Native export bytes differ from frozen checkpoint')
        validation = check_after(checkpoint['session_prefix'], load(canonical), False)
        stage = 'final-sync'
        synced_after = tools.sync_tree(workspace)
        require(reference(destination) == config_pin and mount_status(request['mount'], point)[1] == identity,
                'Source mount or provider configuration changed during preparation')
        result = dict(passed=True, source=source, mount=request['mount'], checkpoint=request['checkpoint'],
            session_id=checkpoint['session_id'], canonical_export=reference(canonical), prefix_validation=validation,
            phase_request=reference(phase_file), bounded_receipt=reference(export/'bounded.json'),
            session_state=dict(workspace=str(workspace),project=str(workspace/'repo'),config=str(destination),xdg=state),
            client_config=config_pin, sync_before_export=synced, sync_after_export=synced_after,
            empty_home=True, model_calls=0, automatic_retry=False,
            scope='Source preparation only; mount retained. No target copy, import, resume, or formal measurement')
        write_new(output/'result.json', result)
        return result
    except BaseException as error:
        write_new(output/'failed.json', dict(stage=stage, error_type=type(error).__name__, automatic_retry=False,
            source_workspace_may_exist=True, mount_retained=True,
            reason=str(error) if type(error) is InstallError else None))
        raise


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--request', required=True)
    parser.add_argument('--sha256', required=True)
    parser.add_argument('--out', required=True)
    args = parser.parse_args()
    try:
        print(json.dumps(run(dict(path=args.request,sha256=args.sha256), args.out)))
    except Exception as error:
        # Do not print exception text that might include a malformed private config.
        print(json.dumps(dict(passed=False,error_type=type(error).__name__,automatic_retry=False,
            reason=str(error) if type(error) is InstallError else None)), file=sys.stderr)
        raise SystemExit(1)
